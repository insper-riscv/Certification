"""Testes da conferência de cobertura dos ELFs, da coleta do resultado de um job e dos números da documentação."""

import argparse
import json
import re
import sys
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "tools/riscv_build"))

import act_docs
import act_inventory
import act_matrix
import act_result
import memory_models
from profile_params import minimal_profiles, minimal_tests

DRY_RUN = """
  /tmp/w/rv32i__x/elfs/rv32i/Zicclsm/Zicclsm-lh-00.elf: gcc -o /tmp/w/rv32i__x/elfs/rv32i/Zicclsm/Zicclsm-lh-00.elf
  /tmp/w/rv32e__x/elfs/rv32e/E/E-add-00.elf: gcc
"""


def test_parse_elfs_reads_base_suite_and_test() -> None:
    """A saída do dry-run vira o conjunto de identificadores base/pasta/teste."""
    assert act_inventory.parse_elfs(DRY_RUN) == {"rv32i/Zicclsm/Zicclsm-lh-00", "rv32e/E/E-add-00"}


def test_compare_reports_both_directions() -> None:
    """Um ELF esperado e não coberto, e um coberto e não esperado, são ambos problemas."""
    assert act_inventory.compare({"a", "b"}, {"a", "b"}) == []
    found = act_inventory.compare({"a", "b"}, {"a", "c"})
    assert found == ["missing from every planned profile: b", "generated by a planned profile but not expected: c"]


def test_check_counts_compares_the_declared_tests() -> None:
    """O campo tests do YAML tem de ser o número de ELFs que o ACT4 gera."""
    assert act_inventory.check_counts({"p": 3, "q": 4}, {"p": 3, "q": 5}) == ["q: minimal_profiles.yaml says tests: 4, ACT4 generates 5"]
    assert act_inventory.check_counts({"p": 3}, {}) != []


def test_by_suite() -> None:
    """A contagem por pasta agrupa por base e pasta."""
    assert act_inventory.by_suite({"rv32i/I/a", "rv32i/I/b", "rv32e/E/a"}) == {"rv32i/I": 2, "rv32e/E": 1}


def test_minimal_profiles_cover_both_bases_and_m_twice() -> None:
    """Há perfis de base E, e o M roda nas duas bases (rv32em e rv32im)."""
    names = {name for name, _ in minimal_profiles(ROOT)}
    assert {"rv32e", "rv32em", "rv32e_zmmul", "rv32em_full", "rv32em_full_zifencei", "rv32im", "rv32im_full"} <= names
    assert minimal_tests(ROOT)["rv32em"] == 51


def test_every_minimal_profile_runs_on_some_memory_model() -> None:
    """Nenhum perfil mínimo fica sem modelo de memória; os com Zifencei têm um só."""
    run, _refused = act_matrix.matrix_entries(minimal_profiles(ROOT), memory_models.all_models())
    jobs: dict[str, int] = {}
    for entry in run:
        jobs[entry["profile"]] = jobs.get(entry["profile"], 0) + 1
    assert set(jobs) == {name for name, _ in minimal_profiles(ROOT)}
    assert {name for name, count in jobs.items() if count == 1} == {name for name, ext in minimal_profiles(ROOT) if "Zifencei" in ext}


@pytest.mark.parametrize("lang", ["pt-br", "en"])
def test_matrix_doc_matches_the_yaml(lang: str) -> None:
    """Os números de matrix.md (perfis, ELFs e jobs) são os que o YAML e a matriz do workflow dão."""
    current = act_docs.doc_path(ROOT, lang).read_text(encoding="utf-8")
    assert act_docs.render(ROOT, lang, current) == current


def test_doc_check_detects_a_wrong_number() -> None:
    """Trocar o total de jobs no texto faz a conferência acusar a diferença."""
    current = act_docs.doc_path(ROOT, "en").read_text(encoding="utf-8")
    wrong = re.sub(r"(<!-- gen:jobs -->)\d+", r"\g<1>99", current)
    assert wrong != current
    assert act_docs.render(ROOT, "en", wrong) == current


LOG = """analyze x
=== E-add-00 ===
E-add-00: PASS

=== Summary ===
  PASS  E-add-00
  FAIL  E-sub-00
"""


def test_parse_summary() -> None:
    """Só o resumo final do log vale, com PASS e FAIL por teste."""
    assert act_result.parse_summary(LOG) == {"E-add-00": True, "E-sub-00": False}
    assert act_result.parse_summary("no summary here") == {}


def test_collect_writes_result_json(tmp_path: Path) -> None:
    """O coletor junta o resumo do log com a pasta dos ELFs e copia os logs."""
    root = tmp_path / "root"
    act = tmp_path / "act4"
    (root / "logs/certification").mkdir(parents=True)
    (root / "logs/certification/latest.log").write_text(LOG)
    (root / "build/target/act/t").mkdir(parents=True)
    (root / "build/target/act/t/test_config.yaml").write_text("name: t\n")
    (root / "build/target/config.yaml").write_text('act:\n  target_config: build/target/act/t/test_config.yaml\n  extensions: "E,M,Zmmul"\n')
    elfs = act / "work/t/elfs/rv32e/E"
    elfs.mkdir(parents=True)
    (elfs / "E-add-00.elf").write_text("")
    (elfs / "E-sub-00.elf").write_text("")
    (elfs / "E-sub-00.sig.elf").write_text("")
    (act / "work/t/test_list.md").write_text("# list\n")
    (tmp_path / ".tag").write_text("e7b9a78869f5839836037e764d4700d71879590b\n4.1.0\n")
    args = argparse.Namespace(
        root=str(root), profile="rv32e", memory="rom=int,ram=int,icache=off,dcache=off", config="build/target/config.yaml",
        out=str(tmp_path / "out"), log="logs/certification/latest.log", vendor_dir=str(act),
    )
    act_result.collect(args)
    data = json.loads((tmp_path / "out/result.json").read_text())
    assert data["results"] == {"rv32e/E/E-add-00": "PASS", "rv32e/E/E-sub-00": "FAIL"}
    assert data["slug"] == "rom-int_ram-int_ic-off_dc-off"
    assert data["extensions"] == ["E", "M", "Zmmul"]
    assert data["act4_commit"] == "e7b9a78869f5839836037e764d4700d71879590b"
    assert (tmp_path / "out/latest.log").read_text() == LOG
    assert (tmp_path / "out/test_list.md").exists()


def test_reference_profiles_drop_the_extensions_of_the_480_matrix(monkeypatch: pytest.MonkeyPatch) -> None:
    """Com a matriz de 480 perfis (Zimop e Zicond na matriz), só os 120 de referência são gerados."""
    import profile_params

    matrix = [("rv32i", set()), ("rv32im", {"M"}), ("rv32i_zimop", {"Zimop"}), ("rv32im_zicond_zicntr", {"M", "Zicond", "Zicntr"})]
    monkeypatch.setattr(profile_params, "variants", lambda _root: matrix)
    assert profile_params.reference_profiles(ROOT) == [("rv32i", set()), ("rv32im", {"M"})]
